import { squadPresets } from '../src/data/squadPresets';
// @vitest-environment jsdom
import { readFileSync } from 'node:fs';
import { expect, test, vi } from 'vitest';
import { buildSquadShareUrl, decodeSquadSharePayload } from './squadShareUtils';
vi.mock('./exploreSquad.js', async original => ({ ...await original(), fetchExploreCards: async () => [{ id: 321, player_id: 123, overall: 91, price: 68000, players: { id: 123, name: 'Explorer Player' }, card_positions: [{ is_primary: true, positions: { name: 'ST' } }] }] }));
const mocks=vi.hoisted(()=>({finish:null,services:null}));
vi.mock('./squadShareHydration.js',()=>({loadSharedSquadCards:vi.fn(async(_db,_payload,normalize)=>{
  await new Promise(resolve=>{mocks.finish=resolve;});
  const card=normalize({id:123,player_id:123,overall:90,price:40000,version:'Gold',players:{id:123,name:'Shared Player',nation_id:52},club_id:1,league_id:13,
    card_positions:[{is_primary:true,positions:{name:'ST'}}],player_stats:[{pac:90,sho:90,def:80,phy:90}],card_playstyles:[],card_roles:[]});
  return {ST:{card,isLocked:true,isOwned:true}};
})}));
vi.mock('./preloadImages.ts',()=>({preloadImages:vi.fn(),preloadCardImages:vi.fn()}));
vi.mock('./playstyleFilters.js',async original=>({...await original(),fetchPlaystyleOptions:async()=>[]}));
vi.mock('./affiliations.js',async original=>({...await original(),fetchAffiliations:async()=>({leagues:[{id:13,name:'League'}],nations:[{id:52,name:'Nation'}],clubs:[]})}));
vi.mock('../components/AutoBuildSettings.jsx',()=>({mountAutoBuildSettings:(_el,_f,_b,services)=>{mocks.services=services;return ()=>{};}}));
vi.mock('../components/Analytics.jsx',()=>({mountAnalytics:()=>{}}));
test('URL hydration applies formation, flags, manager and budget without overwriting saved slots',async()=>{
  vi.stubGlobal('ResizeObserver',class{observe(){}disconnect(){}});
  vi.stubGlobal('matchMedia',()=>({matches:false,addEventListener(){},removeEventListener(){}}));
  vi.stubEnv('VITE_SUPABASE_URL','');vi.stubEnv('VITE_SUPABASE_ANON_KEY','');
  HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new Event('close'));};
  const payload={version:'v1',formation:'4-3-3',slots:Array(11).fill(null),manager:{leagueId:'13',nationId:'52'},budget:1000000};
  payload.slots[1]={cardVersionId:'123',isLocked:true,isOwned:true};
  history.replaceState(null,'',buildSquadShareUrl(location.origin+'/',payload));
  localStorage.setItem('metaxi_saved_slots','[]');
  const write=vi.spyOn(Storage.prototype,'setItem');
  document.documentElement.innerHTML=readFileSync('index.html','utf8');
  await import('../main.js');
  expect(document.querySelector('.squad-share-loading')).not.toBeNull();
  expect(document.querySelector('.squad-workspace').inert).toBe(true);
  mocks.finish();
  await vi.waitFor(()=>expect(document.querySelector('.squad-share-loading')).toBeNull());
  expect(document.querySelector('#formation-current').textContent).toBe('4-3-3');
  const slot=document.querySelector('.slot[data-position="ST"]');
  expect(slot.classList.contains('is-locked')).toBe(true);expect(slot.classList.contains('is-owned')).toBe(true);
  expect(document.querySelector('#target-budget').value).toBe('1,000,000');
  expect(document.querySelector('#manager-slot').textContent).toContain('League');
  expect(document.querySelector('#total-cost').value).toBe('0');
  expect(write.mock.calls.filter(([key])=>key==='metaxi_saved_slots')).toEqual([]);
  document.querySelector('.squad-share-trigger').click();
  const exported=decodeSquadSharePayload(new URL(document.querySelector('.share-url').value).searchParams.get('s'));
  expect(exported).toEqual(payload);
  expect(document.querySelector('.share-summary').textContent).toContain('90.0');
  const workspace = document.querySelector('.squad-workspace');
  expect(workspace.dataset.panel).toBe('build');
  document.querySelector('.explore-edge-tab').click();
  expect(workspace.dataset.panel).toBe('explore');
  const tile = document.querySelector('.explore-tile');
  const transfer = { types: ['application/x-squad-explore'], setData: vi.fn() };
  const start = new Event('dragstart'); start.dataTransfer = transfer; tile.dispatchEvent(start);
  expect(slot.classList.contains('explore-compatible')).toBe(true);
  const badDrop = new Event('drop'); badDrop.dataTransfer = transfer;
  document.querySelector('.slot[data-position="GK"]').dispatchEvent(badDrop);
  expect(document.querySelector('.slot[data-position="GK"]').classList.contains('occupied')).toBe(false);
  tile.dispatchEvent(start);
  const drop = new Event('drop'); drop.dataTransfer = transfer; slot.dispatchEvent(drop);
  expect(workspace.dataset.panel).toBe('explore');
  expect(slot.classList.contains('is-locked')).toBe(true);
  expect(slot.dataset.card).toBe('Explorer Player');
  await new Promise(resolve => setTimeout(resolve, 1));
  document.querySelector('.pitch').click(); expect(workspace.dataset.panel).toBe('explore');
  slot.querySelector('.slot-card-body').click(); expect(workspace.dataset.panel).toBe('explore');
  for (const width of [1440, 1100, 900, 600, 1440]) {
    Object.defineProperty(window, 'innerWidth', { configurable: true, value: width });
    window.dispatchEvent(new Event('resize'));
    expect(workspace.dataset.panel).toBe('explore');
  }
  tile.dispatchEvent(new Event('dragend'));
  await new Promise(resolve => setTimeout(resolve, 360));
  document.querySelector('.explore-mobile-toggle').click();
  const beforeDetail = mocks.services.getSquadSnapshot();
  tile.click();
  expect(workspace.classList.contains('explore-drawer-open')).toBe(true);
  expect(workspace.dataset.panel).toBe('explore');
  expect(mocks.services.getSquadSnapshot()).toBe(beforeDetail);
  expect(document.querySelector('#player-detail-modal').hidden).toBe(false);
  expect(slot.dataset.card).toBe('Explorer Player');
  document.querySelector('#player-detail-close').click();
  expect(workspace.classList.contains('explore-drawer-open')).toBe(true);
  expect(mocks.services.getSquadSnapshot()).toBe(beforeDetail);
  document.querySelector('.explore-backdrop').click();
  slot.querySelector('.lock-player').click(); expect(workspace.dataset.panel).toBe('build');
  document.querySelector('.explore-edge-tab').click();
  document.querySelector('.slot[data-position="GK"]').click(); expect(workspace.dataset.panel).toBe('build');
  document.querySelector('.explore-edge-tab').click();
  document.querySelector('.explore-presets button').click();
  mocks.finish();
  await vi.waitFor(() => expect(workspace.dataset.panel).toBe('build'));
  expect(document.querySelector('#formation-current').textContent).toBe(decodeSquadSharePayload(squadPresets[0].shareCode).formation);
  document.querySelector('.explore-mobile-toggle').click(); tile.click();
  const add = document.querySelector('.player-detail-add'); expect(add.hidden).toBe(false);
  expect(document.querySelector('.slot[data-position="LS"]').classList.contains('occupied')).toBe(false);
  add.click();
  await vi.waitFor(() => expect(document.querySelector('#player-detail-modal').hidden).toBe(true));
  expect(document.querySelector('.slot[data-position="LS"]').classList.contains('is-locked')).toBe(true);
  expect(workspace.classList.contains('explore-drawer-open')).toBe(false);
});
