// @vitest-environment jsdom
import { readFileSync } from 'node:fs';
import { beforeAll, expect, test, vi } from 'vitest';
import { setLanguage } from '../src/i18n/languageStore';
const bridge = vi.hoisted(() => ({ services: null }));
vi.mock('./playstyleFilters.js', async original => ({ ...(await original()), fetchPlaystyleOptions: async () => [] }));
vi.mock('./affiliations.js', async original => ({ ...(await original()), fetchAffiliations: async () => ({ leagues: [], nations: [], clubs: [] }) }));
vi.mock('../components/AutoBuildSettings.jsx', () => ({ mountAutoBuildSettings: (_el, _formation, _budget, services) => { bridge.services = services; return () => {}; } }));
beforeAll(async () => {
  vi.stubGlobal('matchMedia', () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
  vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} });
  vi.stubEnv('VITE_SUPABASE_URL', ''); vi.stubEnv('VITE_SUPABASE_ANON_KEY', '');
  document.documentElement.innerHTML = readFileSync('index.html', 'utf8');
  HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  await import('../main.js'); setLanguage('en', false);
});
test('physical tab restores per-slot choices, language, indicators and both reset paths without clearing stars', () => {
  bridge.services.openTacticalRoles();
  const dialog = document.querySelector('.tactical-roles-dialog');
  expect(dialog.querySelectorAll('[data-tab]')).toHaveLength(4);
  const slots = [...dialog.querySelectorAll('[data-slot]')].map(node => node.dataset.slot);
  const [first, second] = slots;
  const select = slot => dialog.querySelector(`[data-slot="${slot}"]`).click();
  const choice = (key, value) => dialog.querySelector(`[data-physical="${key}"][data-value="${value}"]`);
  select(first);
  dialog.querySelector('[aria-label="Skill Moves ★4+"]').click();
  dialog.querySelector('[data-tab="physical"]').click();
  choice('bodyTypes', 'Unique').click(); choice('acceleTypes', 'Explosive').click();
  const height = dialog.querySelector('[data-physical="minHeight"]'); height.value = '180'; height.dispatchEvent(new Event('input'));
  expect(dialog.querySelector('[data-physical="minAge"]')).toBeNull();
  expect(bridge.services.getRoleOptions().slotRequirements[first]).toMatchObject({ minSm: 4, physical: { bodyTypes: ['Unique'], acceleTypes: ['Explosive'], minHeight: 180 } });
  expect(dialog.querySelector(`[data-slot="${first}"] .tactical-role-dot`)).not.toBeNull();
  select(second); expect(choice('bodyTypes', 'Unique').getAttribute('aria-pressed')).toBe('false');
  choice('bodyTypes', 'Stocky Short').click();
  select(first); expect(choice('bodyTypes', 'Unique').getAttribute('aria-pressed')).toBe('true');
  expect(dialog.querySelector('[data-physical="minHeight"]').value).toBe('180');
  setLanguage('ko', false);
  expect(dialog.querySelector('[data-tab="physical"]').textContent).toContain('피지컬 & 체형');
  expect(dialog.querySelector('.role-all-chip').textContent).toBe('이 슬롯 피지컬 & 체형 해제');
  dialog.querySelector('.role-all-chip').click();
  expect(bridge.services.getRoleOptions().slotRequirements[first]).toEqual({ minSm: 4 });
  expect(bridge.services.getRoleOptions().slotRequirements[second].physical.bodyTypes).toEqual(['Stocky Short']);
  dialog.querySelector('.tactical-clear-all').click();
  expect(bridge.services.getRoleOptions().slotRequirements).toEqual({});
  expect(dialog.querySelectorAll('.tactical-role-dot')).toHaveLength(0);
  choice('bodyTypes', 'Unique').click(); bridge.services.clearRolesAndPlaystyles();
  expect(bridge.services.getRoleOptions().slotRequirements).toEqual({});
  dialog.dispatchEvent(new Event('close')); setLanguage('en', false);
});

test('four translated tabs store and reset detailed stats per slot and category', () => {
  bridge.services.openTacticalRoles();
  const dialog = document.querySelector('.tactical-roles-dialog');
  expect([...dialog.querySelectorAll('[data-tab]')].map(node => node.dataset.tab)).toEqual(['roles', 'playstyles', 'stats', 'physical']);
  const slots = [...dialog.querySelectorAll('[data-slot]')].map(node => node.dataset.slot).filter(slot => slot !== 'GK');
  dialog.querySelector(`[data-slot="${slots[0]}"]`).click();
  dialog.querySelector('[data-tab="stats"]').click();
  const set = (key, value) => { const input = dialog.querySelector(`[data-stat="${key}"][data-bound="min"]`); input.value = value; input.dispatchEvent(new Event('input')); };
  expect(dialog.querySelector('details[open] summary').textContent).toContain('PACE');
  set('finishing', '88'); set('composure', '85');
  expect(bridge.services.getRoleOptions().slotRequirements[slots[0]].detailedStats).toEqual({ finishing: { min: 88 }, composure: { min: 85 } });
  expect(dialog.querySelector('[data-tab="stats"] .tactical-count').textContent).toBe('2');
  dialog.querySelector('[data-slot="GK"]').click();
  expect(dialog.querySelector('details[open] summary').textContent).toContain('GOALKEEPING');
  set('gk_diving', '90');
  dialog.querySelector(`[data-slot="${slots[0]}"]`).click();
  expect(dialog.querySelector('[data-stat="finishing"][data-bound="min"]').value).toBe('88');
  dialog.querySelector('[aria-label="SHOOTING Clear"]').click();
  expect(bridge.services.getRoleOptions().slotRequirements[slots[0]].detailedStats).toEqual({ composure: { min: 85 } });
  setLanguage('ko', false);
  expect([...dialog.querySelectorAll('[data-tab]')].map(node => node.textContent)).toEqual(['🎭 롤', '⚡ 플레이스타일', '📈 세부 스탯1', '⚙️ 피지컬 & 체형']);
  expect(dialog.querySelector('.role-all-chip').textContent).toBe('이 슬롯 세부 스탯 해제');
  dialog.querySelector('.role-all-chip').click();
  expect(bridge.services.getRoleOptions().slotRequirements[slots[0]]).toBeUndefined();
  expect(bridge.services.getRoleOptions().slotRequirements.GK.detailedStats).toBeDefined();
  dialog.querySelector('.tactical-clear-all').click();
  expect(bridge.services.getRoleOptions().slotRequirements).toEqual({});
  dialog.dispatchEvent(new Event('close')); setLanguage('en', false);
});
